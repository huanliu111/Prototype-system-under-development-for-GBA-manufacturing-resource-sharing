def _translate_text(text: str) -> str:
    if not text or not re.search(r'[\u4e00-\u9fff]', text):
        return text
    result = text
    # Longest phrase first so complete sentences win over terms inside them.
    for zh in sorted(PHrases, key=len, reverse=True):
        if zh in result:
            result = result.replace(zh, PHrases[zh])
    # Numeric counters and mixed phrases that templates assemble dynamically.
    patterns = [
        (r'(\d+)\s*个需求记录', r'\1 demand records'),
        (r'(\d+)\s*个供给窗口', r'\1 supply windows'),
        (r'(\d+)\s*个已完成', r'\1 completed'),
        (r'(\d+)\s*类', r'\1 categories'),
        (r'(\d+)\s*家', r'\1 companies'),
        (r'(\d+)\s*条', r'\1 records'),
        (r'(\d+)\s*步', r'\1 steps'),
        (r'(\d+)\s*轮', r'\1 iterations'),
        (r'(\d+)\s*笔成交', r'\1 trades'),
        (r'共\s*(\d+)', r'Total \1'),
        (r'第\s*(\d+)\s*轮', r'iteration \1'),
    ]
    for pattern, replacement in patterns:
        result = re.sub(pattern, replacement, result)
    # Clean up residual common particles only when they survive as standalone
    # Chinese text; business codes and user-entered identifiers are untouched.
    for zh, en in (('，', ', '), ('。', '. '), ('；', '; '), ('：', ': '),
                  ('（', ' ('), ('）', ')'), ('、', ', ')):
        result = result.replace(zh, en)
    # Clean artifacts produced by term-by-term replacement.
    result = result.replace('sharingtasks', 'sharing tasks')
    result = result.replace('companiesBuyer', 'buyer companies').replace('companiesSupplier', 'supplier companies')
    result = result.replace('machine-hour(s)', 'machine-hours')
    return result


def _translate_attr(value: str) -> str:
    return _translate_text(value)


def translate_html(html: str) -> str:
    soup = BeautifulSoup(html, 'html.parser')
    if soup.html is not None:
        soup.html['lang'] = 'en'
    for node in list(soup.find_all(string=True)):
        parent = getattr(node, 'parent', None)
        if parent is not None and parent.name in {'script', 'style'}:
            continue
        new = _translate_text(str(node))
        if new != str(node):
            node.replace_with(NavigableString(new))
    for tag in soup.find_all(True):
        for attr in ('placeholder', 'title', 'aria-label', 'alt'):
            if tag.has_attr(attr) and isinstance(tag.get(attr), str):
                tag[attr] = _translate_attr(tag[attr])
    return str(soup)

